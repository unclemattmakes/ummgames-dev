// The sweeps behind SWEPT: each function over these inputs, folded by `fold`.
/** FNV-1a over the float64 bits of `values`, as 8 hex digits. @param {number[]} values */
export function fold(values) {
  const buf = new DataView(new ArrayBuffer(8))
  let h = 0x811c9dc5
  for (const v of values) {
    buf.setFloat64(0, v)
    for (let i = 0; i < 8; i++) {
      h ^= buf.getUint8(i)
      h = Math.imul(h, 0x01000193)
    }
  }
  return (h >>> 0).toString(16).padStart(8, '0')
}
